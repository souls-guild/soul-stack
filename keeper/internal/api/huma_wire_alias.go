// The Operator API wire types are declared in shared/api/wire, not here: soulctl and the
// e2e/load harnesses speak this contract too, and an internal/ package forces every one of
// them to retype it (NIM-776). These are ALIASES, not copies - an alias declares no fields
// of its own, so a tag edited in shared/api/wire lands here, in soulctl and in the harnesses
// in the same compile. They exist so the handlers, projections and golden tests in this
// package keep naming the types unqualified.
//
// The three enums with a NAMED schema (SoulStatus / SoulTransport / IncarnationStatus) keep
// their huma.SchemaProvider on a keeper-local shim registered as a type alias - the enum
// values are contract, the schema emission is server-side. See huma_soul_status.go.

